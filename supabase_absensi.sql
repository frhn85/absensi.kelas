-- Jalankan di Supabase SQL Editor sebagai project owner. Backup database lebih dulu.

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique,
  role text not null default 'user' check (role in ('user','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.students (
  id bigint generated by default as identity primary key,
  nis text not null unique,
  nama text not null,
  kelas text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.schedules (
  id bigint generated by default as identity primary key,
  hari text not null,
  mata_pelajaran text not null,
  guru text,
  jam text,
  kelas text,
  created_at timestamptz not null default now()
);

create table if not exists public.absensi (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  username text not null,
  nama text not null,
  kelas text not null,
  tanggal date not null default current_date,
  status text not null check (status in ('Hadir','Izin','Sakit','Alpa','Bolos')),
  keterangan text,
  created_at timestamptz not null default now()
);

create index if not exists absensi_user_id_idx on public.absensi(user_id);
create index if not exists absensi_tanggal_idx on public.absensi(tanggal desc);
create unique index if not exists absensi_one_per_user_per_day_idx on public.absensi(user_id, tanggal);

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public
as $$
  select exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin');
$$;
revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

alter table public.profiles enable row level security;
alter table public.students enable row level security;
alter table public.schedules enable row level security;
alter table public.absensi enable row level security;

-- Profiles: user can read own profile; admin can manage all profiles.
drop policy if exists profiles_read_self_admin on public.profiles;
create policy profiles_read_self_admin on public.profiles for select to authenticated
using (id = auth.uid() or public.is_admin());
drop policy if exists profiles_admin_all on public.profiles;
create policy profiles_admin_all on public.profiles for all to authenticated
using (public.is_admin()) with check (public.is_admin());

-- Student and schedule master data: readable after login, writable by admin only.
drop policy if exists students_read_authenticated on public.students;
create policy students_read_authenticated on public.students for select to authenticated using (true);
drop policy if exists students_admin_all on public.students;
create policy students_admin_all on public.students for all to authenticated
using (public.is_admin()) with check (public.is_admin());
drop policy if exists schedules_read_authenticated on public.schedules;
create policy schedules_read_authenticated on public.schedules for select to authenticated using (true);
drop policy if exists schedules_admin_all on public.schedules;
create policy schedules_admin_all on public.schedules for all to authenticated
using (public.is_admin()) with check (public.is_admin());

-- Students see their own attendance; admins see/manage all attendance.
drop policy if exists attendance_read_self_admin on public.absensi;
create policy attendance_read_self_admin on public.absensi for select to authenticated
using (user_id = auth.uid() or public.is_admin());
drop policy if exists attendance_insert_self on public.absensi;
create policy attendance_insert_self on public.absensi for insert to authenticated
with check (user_id = auth.uid());
drop policy if exists attendance_admin_update on public.absensi;
create policy attendance_admin_update on public.absensi for update to authenticated
using (public.is_admin()) with check (public.is_admin());
drop policy if exists attendance_admin_delete on public.absensi;
create policy attendance_admin_delete on public.absensi for delete to authenticated
using (public.is_admin());

-- Minimal table privileges; RLS remains the actual row-level gate.
grant usage on schema public to authenticated;
grant select, insert, update, delete on public.profiles to authenticated;
grant select, insert, update, delete on public.students to authenticated;
grant select, insert, update, delete on public.schedules to authenticated;
grant select, insert, update, delete on public.absensi to authenticated;
grant usage, select on all sequences in schema public to authenticated;

